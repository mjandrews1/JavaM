package mjvm.runtime;

import java.lang.invoke.CallSite;
import java.lang.invoke.ConstantCallSite;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;

/**
 * mJVM M3 — invokedynamic bootstrap for DO/$$/GOTO call sites.
 *
 * Generated classes call
 *   INVOKEDYNAMIC call:(Lmjvm/runtime/MRuntime;Ljava/lang/String;I)V
 * with bootstrap {@link #call} / {@link #goto_}.
 */
public final class Indy {

    private Indy() {}

    /** Bootstrap for DO / $$ — link to {@link MRuntime#call}. */
    public static CallSite call(MethodHandles.Lookup lookup, String name, MethodType type,
                                String mname, int argc) throws Throwable {
        MethodHandle target = MethodHandles.lookup()
                .findVirtual(MRuntime.class, "call", MethodType.methodType(void.class,
                        String.class, int.class));
        // drop the MRuntime receiver from the static call site type if needed
        MethodHandle bound = target;
        if (type.parameterCount() == 3 && type.parameterType(0) == MRuntime.class) {
            // call(MRuntime, String, int) — already matches
        }
        return new ConstantCallSite(bound.asType(type));
    }

    /** Bootstrap for GOTO tag^rtn — same linkage, different name for tracing. */
    public static CallSite goto_(MethodHandles.Lookup lookup, String name, MethodType type,
                                 String mname, int argc) throws Throwable {
        MethodHandle target = MethodHandles.lookup()
                .findVirtual(MRuntime.class, "call", MethodType.methodType(void.class,
                        String.class, int.class));
        return new ConstantCallSite(target.asType(type));
    }

    /** WRITE helper used by generated bytecode (non-indy). */
    public static void write(MRuntime rt, String s) {
        rt.write(s);
    }
}
